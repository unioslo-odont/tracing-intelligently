"""
================================================================================
FOLD MANIFEST - the patient->fold mapping as a private, asserted artifact
================================================================================
DESCRIPTION:
    The k-fold split is a pure function of (patient serials, k, seed) - see
    kfold.assign_patient_folds - so historically every run just regenerated
    it. That is fine as long as the *patient set* never changes, and silently
    wrong the moment it does: adding a re-extracted patient, or changing the
    exclusion list, re-deals EVERY patient into a different fold, so a "fold 3"
    trained today would hold out different people than the "fold 3" of Run 6.
    Cross-run comparisons (Run 6 vs Run 7, or a label-efficiency curve whose
    100% point is reused from Run 6) would then be meaningless while still
    looking perfectly reasonable in the output tables.

    So from Run 7/8/9 on, the mapping is PERSISTED once (configs/folds/*.csv,
    retained privately) and every run ASSERTS against it instead of trusting
    regeneration:
      1. the dataset's patient set must equal the manifest's, exactly
         (catches changed exclusions / new or lost patients), and
      2. the mapping recomputed from (k, seed) must equal the manifest
         (catches a changed RNG, numpy version, or split implementation).
    Any mismatch raises with the specific patients involved rather than
    quietly producing a different experiment.

    Failure here is not a nuisance to work around: it means the split about to
    be trained is NOT the split Run 6 was evaluated on. Either restore the old
    data/exclusions, or regenerate the manifest and re-run everything that will
    be compared against it.

FORMAT (configs/folds/<name>.csv):
    '#'-prefixed metadata lines, then a 'patient_serial,fold' table sorted by
    serial - diffable, greppable, and small enough to review in a PR.

USAGE:
    generate:  python code/training/make_fold_manifest.py --config configs/unet_baseline.yaml
    consume:   kfold.manifest_path in a config (see resolve_kfold_split below)
================================================================================
"""

import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kfold import assign_patient_folds, splits_from_fold_map, make_patient_kfold_splits


def resolve_relative(path, base_dir):
    """Resolve a config-relative path against the config file's own directory
    (same convention as data.landmark_config_path / data.exclude_images_path)."""
    if not path or os.path.isabs(path):
        return path
    return os.path.join(base_dir, path) if base_dir else path


def write_fold_manifest(path, fold_of_serial, meta=None):
    """Write {serial: fold} as a '#'-commented, sorted CSV."""
    os.makedirs(os.path.dirname(os.path.abspath(path)) or '.', exist_ok=True)
    with open(path, 'w', newline='', encoding='utf-8') as f:
        for key, value in (meta or {}).items():
            f.write(f"# {key}: {value}\n")
        f.write("# Generated by code/training/make_fold_manifest.py - DO NOT hand-edit.\n")
        f.write("# Every training/eval run with kfold.manifest_path set asserts against this file;\n")
        f.write("# regenerating it invalidates comparisons against runs made under the old mapping.\n")
        writer = csv.writer(f)
        writer.writerow(['patient_serial', 'fold'])
        for serial in sorted(fold_of_serial):
            writer.writerow([serial, fold_of_serial[serial]])


def read_fold_manifest(path):
    """Return ({serial: fold}, {meta_key: value}) from a manifest CSV."""
    fold_of_serial, meta, rows = {}, {}, []
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if line.startswith('#'):
                key, sep, value = line[1:].partition(':')
                if sep:
                    meta[key.strip()] = value.strip()
                continue
            rows.append(line)
    for row in csv.DictReader(rows):
        fold_of_serial[row['patient_serial'].strip()] = int(row['fold'])
    if not fold_of_serial:
        raise ValueError(f"Fold manifest {path} contains no patient rows")
    return fold_of_serial, meta


def verify_fold_map(dataset_serials, manifest_map, k, seed, manifest_path='<manifest>'):
    """Assert that `manifest_map` still describes this dataset and this (k, seed).

    Raises RuntimeError naming the offending patients. Returns the manifest map
    on success (that map, not a regenerated one, is what callers must split on)."""
    dataset_serials = set(dataset_serials)
    manifest_serials = set(manifest_map)

    only_in_data = sorted(dataset_serials - manifest_serials)
    only_in_manifest = sorted(manifest_serials - dataset_serials)
    if only_in_data or only_in_manifest:
        raise RuntimeError(
            f"Fold manifest {manifest_path} does not match the dataset: "
            f"{len(only_in_data)} patient(s) in the data but not the manifest "
            f"(e.g. {only_in_data[:5]}), "
            f"{len(only_in_manifest)} in the manifest but not the data "
            f"(e.g. {only_in_manifest[:5]}). The k-fold split is dealt over the patient "
            "set as a whole, so ANY change to it re-deals every fold and breaks comparability "
            "with the runs this manifest was made for. Check data.exclude_images_path, the "
            "review CSV, and the extraction; only regenerate the manifest if you intend to "
            "re-run every arm that will be compared."
        )

    recomputed = assign_patient_folds(dataset_serials, k=k, seed=seed)
    disagreeing = sorted(s for s in manifest_map if recomputed[s] != manifest_map[s])
    if disagreeing:
        raise RuntimeError(
            f"Fold manifest {manifest_path} disagrees with the split recomputed from "
            f"(k={k}, seed={seed}) for {len(disagreeing)} patient(s), e.g. "
            f"{[(s, manifest_map[s], recomputed[s]) for s in disagreeing[:5]]} "
            "(serial, manifest_fold, recomputed_fold). The patient set matches, so this is a "
            "changed k/seed or a changed split implementation (kfold.assign_patient_folds / "
            "numpy RNG). The manifest is authoritative - fix the config or the code."
        )
    return manifest_map


def resolve_kfold_split(base_dataset, config, fold, config_dir=None, verbose=True):
    """Return (train_idx, val_idx) for `fold`, honouring kfold.manifest_path.

    With a manifest: verify it against this dataset and (k, seed), then split
    ON THE MANIFEST (never on a regenerated mapping). Without one: the legacy
    regenerate-from-seed path, bit-identical to what Runs 1-6 did."""
    k = config['kfold']['k']
    seed = config['seed']
    manifest_path = resolve_relative((config.get('kfold') or {}).get('manifest_path'), config_dir)

    if not manifest_path:
        if verbose:
            print(f"[folds] kfold.manifest_path not set - regenerating the split from "
                  f"(k={k}, seed={seed}). Set it to assert against configs/folds/*.csv instead.")
        return make_patient_kfold_splits(base_dataset, k=k, seed=seed)[fold]

    if not os.path.exists(manifest_path):
        raise RuntimeError(
            f"kfold.manifest_path points at {manifest_path}, which does not exist. The fold mapping "
            "is asserted, not regenerated - generate it once against the canonical data config and "
            "retain it privately (never publish patient IDs):\n"
            "    python code/training/make_fold_manifest.py --config configs/unet_baseline.yaml"
        )

    manifest_map, meta = read_fold_manifest(manifest_path)
    verify_fold_map({e['serial'] for e in base_dataset.samples}, manifest_map,
                    k=k, seed=seed, manifest_path=manifest_path)
    if verbose:
        generated = f", generated {meta['generated']}" if 'generated' in meta else ""
        print(f"[folds] verified against {manifest_path} "
              f"({len(manifest_map)} patients, k={k}, seed={seed}{generated})")
    return splits_from_fold_map(base_dataset, manifest_map, k)[fold]


def train_patients_for_fold(fold_of_serial, fold):
    """Patients on the TRAIN side of `fold`, sorted. Data-independent: needs
    only the manifest, so subset sampling can run off-cluster where the images
    aren't available."""
    return sorted(s for s, f in fold_of_serial.items() if f != fold)


def val_patients_for_fold(fold_of_serial, fold):
    """Patients held OUT in `fold`, sorted."""
    return sorted(s for s, f in fold_of_serial.items() if f == fold)
